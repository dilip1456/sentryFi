import { describe, it, expect } from "vitest";

// The edge functions run a copy of src/lib/classify (Deno can't import from
// src/). scripts/sync-classifier.mjs writes it; this test fails on drift.
const BANNER = "// GENERATED by scripts/sync-classifier.mjs from src/lib/classify. Do not edit here.\n";
const src = import.meta.glob("../lib/classify/*.ts", { query: "?raw", import: "default", eager: true }) as Record<string, string>;
const dst = import.meta.glob("../../supabase/functions/_shared/classify/*.ts", { query: "?raw", import: "default", eager: true }) as Record<string, string>;
const byName = (m: Record<string, string>) => Object.fromEntries(Object.entries(m).map(([k, v]) => [k.split("/").pop()!, v]));

describe("edge-function classifier copy", () => {
  const a = byName(src), b = byName(dst);
  it("matches src/lib/classify exactly (run `node scripts/sync-classifier.mjs`)", () => {
    expect(Object.keys(b).sort()).toEqual(Object.keys(a).sort());
    for (const f of Object.keys(a)) expect(b[f], f).toBe(BANNER + a[f]);
  });
  it("is Deno-safe: only relative .ts imports", () => {
    for (const code of Object.values(a)) {
      for (const m of code.matchAll(/from\s+"([^"]+)"/g)) expect(m[1]).toMatch(/^\.\/[\w-]+\.ts$/);
    }
  });
});
