#!/usr/bin/env node
// Copies the shared transaction classifier (src/lib/classify/*.ts) into
// supabase/functions/_shared/classify/ so Deno edge functions run the exact
// same code as the app. Run after editing src/lib/classify:
//   node scripts/sync-classifier.mjs
// src/test/classify-sync.test.ts fails if the copies drift.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src/lib/classify");
const dst = join(root, "supabase/functions/_shared/classify");
export const BANNER = "// GENERATED by scripts/sync-classifier.mjs from src/lib/classify. Do not edit here.\n";

rmSync(dst, { recursive: true, force: true });
mkdirSync(dst, { recursive: true });
const files = readdirSync(src).filter(f => f.endsWith(".ts"));
for (const f of files) writeFileSync(join(dst, f), BANNER + readFileSync(join(src, f), "utf8"));
console.log(`synced ${files.length} files → supabase/functions/_shared/classify`);
